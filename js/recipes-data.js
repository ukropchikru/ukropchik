/* Считаем КБЖУ и метки рецептов, и добавляем рецепты в справочник продуктов — их можно выбрать в рационе и дневнике */
(function () {
  const food = Object.fromEntries(window.FOODS.map((f) => [f.id, f]));
  const flags = window.FOOD_FLAGS;
  const has = (r, list) => r.items.some(([id]) => list.includes(id));

  window.RECIPES.forEach((r) => {
    const sum = { g: 0, kcal: 0, p: 0, f: 0, c: 0 };
    r.items.forEach(([id, g]) => {
      const x = food[id];
      sum.g += g;
      sum.kcal += (x.kcal * g) / 100;
      sum.p += (x.p * g) / 100;
      sum.f += (x.f * g) / 100;
      sum.c += (x.c * g) / 100;
    });
    r.portion = sum.g;
    r.total = { kcal: Math.round(sum.kcal), p: Math.round(sum.p), f: Math.round(sum.f), c: Math.round(sum.c) };
    r.tags = [];
    if (!has(r, flags.meat)) r.tags.push('veg');
    if (!has(r, flags.animal)) r.tags.push('vegan');
    if (!has(r, flags.gluten)) r.tags.push('gf');
    if (!has(r, flags.dairy)) r.tags.push('lf');
    if (r.time <= 15) r.tags.push('quick');

    const k = 100 / sum.g;
    window.FOODS.push({
      id: 'r_' + r.id,
      cat: 'Рецепты',
      name: r.title,
      kcal: Math.round(sum.kcal * k),
      p: +(sum.p * k).toFixed(1),
      f: +(sum.f * k).toFixed(1),
      c: +(sum.c * k).toFixed(1),
      portion: sum.g,
      recipe: r.id,
    });
  });
})();

